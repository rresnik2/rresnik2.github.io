const gallopLegs = (shift = 0): Leg[] => [
  { hip: [19 - shift, 25], near: true, phase: 0 },
  { hip: [17 - shift, 25], near: false, phase: 0.1 },
  { hip: [8, 25], near: true, phase: 0.5 },
  { hip: [6, 25], near: false, phase: 0.6 },
];

// An 8-frame gallop: each paw down for under a third of the stride, sweeping
// 4.5px either side of its hip; between the front and hind pairs' landings he's
// off the ground, body at its highest
const GALLOP = {
  frames: 8,
  swing: "x" as const,
  reach: 4.5,
  lift: 2,
  duty: 0.3,
  bob: [0, 0, -1, -2, -1, 0, -1, -2],
  tails: TAIL_STREAM,
};

// Running toward or away from the visitor: the same rhythm, paws lifting
const BOUND = { frames: 8, swing: "y" as const, reach: 1, lift: 2, duty: GALLOP.duty, bob: GALLOP.bob };

const RIGS: Rig[] = [
  { name: "run_E", torso: TORSO_SIDE, head: { part: HEAD_SIDE_EARS_BACK, x: 17, y: 9 }, legs: gallopLegs(), ...GALLOP },
  { name: "run_SE", torso: TORSO_DIAGONAL, head: { part: HEAD_THREE_QUARTER, x: 13, y: 8 }, legs: gallopLegs(3), ...GALLOP },
  { name: "run_NE", torso: TORSO_DIAGONAL_AWAY, head: { part: HEAD_BACK_THREE_QUARTER, x: 14, y: 9 }, legs: gallopLegs(3), ...GALLOP },
  // Running away: a bouncing, butt-up bound, hind legs kicking out wide
  {
    name: "run_N",
    torso: TORSO_RUMP,
    head: { part: HEAD_BACK_SMALL, x: 10, y: 11 },
    headBehind: true,
    legs: rumpLegs(2),
    tails: [TAIL_HOOK[0], TAIL_HOOK[0], TAIL_HOOK[2], TAIL_HOOK[2], TAIL_HOOK[0], TAIL_HOOK[0], TAIL_HOOK[1], TAIL_HOOK[1]],
    tailOverHead: true,
    soles: true,
    ...BOUND,
    lift: 2,
  },
  { name: "run_S", torso: TORSO_FRONT, head: { part: HEAD_FRONT, x: 9, y: 4 }, legs: frontLegs, tails: TAIL_FRONT, ...BOUND },
];

export const RUN_FRAMES: Record<string, Frame> = Object.assign({}, ...RIGS.map(buildGait));

const names = (rig: string, count: number) => Array.from({ length: count }, (_, i) => `${rig}_${i + 1}`);

export const RUN_ANIMATIONS: Partial<Record<AnimationName, AnimationDef>> = {
  run: {
    frames: {
      E: names("run_E", 8),
      SE: names("run_SE", 8),
      NE: names("run_NE", 8),
      N: names("run_N", 8),
      S: names("run_S", 8),
    },
    // Body travel per frame that keeps planted paws planted, from the gallop rig
    stride: noSkateStride(GALLOP),
  },
};
