// Breathing in: the back rises a pixel
function breathe(body: Grid, top: number): Grid {
  const rows = [...body.rows];
  rows[top - 1] = rows[top];
  return { ...body, rows };
}

// content: eyes shut happily, being stroked
const loaf = (name: string, body: Grid, headY: number, content = false) =>
  defineFrame(name, {
    body,
    stamps: [{ part: HEAD_FRONT, x: 9, y: headY }, ...(content ? [{ part: EYES_CONTENT, x: 11, y: headY + 6 }] : [])],
  });

const curl = (name: string, body: Grid, content = false) =>
  defineFrame(name, {
    body,
    stamps: [
      { part: HEAD_FRONT, x: 3, y: 13 },
      { part: content ? EYES_CONTENT : EYES_CLOSED, x: 5, y: 19 },
    ],
  });

