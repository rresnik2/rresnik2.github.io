const HEAD_X = 9;
const HEAD_Y = 2;

function sitFront(name: string, { headX = HEAD_X, tail = TAIL_REST, overlays = [] as Stamp[] } = {}) {
  return defineFrame(name, {
    body: SIT_FRONT_BODY,
    stamps: [{ part: HEAD_FRONT, x: headX, y: HEAD_Y }, { part: tail, x: 27, y: 20 }, ...overlays],
  });
}

// Overlays are placed relative to the head, so they follow it when it turns
const eyes = (part: typeof EYES_HALF, headX = HEAD_X): Stamp => ({ part, x: headX + 2, y: HEAD_Y + 6 });

export const SIT_FRONT = sitFront("sit_front");

